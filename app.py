"""Streamlit chat UI. Run with: streamlit run app.py"""

from __future__ import annotations

import dataclasses

import streamlit as st

from rag.config import Settings
from rag.pipeline import RAGPipeline

st.set_page_config(page_title="Local RAG Assistant", page_icon="📚")
st.title("📚 Local RAG Assistant")
st.caption("Answers come only from your documents, generated by a model running on this machine.")

with st.sidebar:
    st.header("Settings")
    defaults = Settings()
    llm_model = st.text_input("LLM (Ollama)", defaults.llm_model)
    top_k = st.slider("Passages to retrieve (k)", 1, 10, defaults.top_k)
    reindex = st.button("Re-index documents")


@st.cache_resource
def get_pipeline(model: str) -> RAGPipeline:
    return RAGPipeline(dataclasses.replace(Settings(), llm_model=model))


pipeline = get_pipeline(llm_model)

if reindex:
    with st.spinner("Embedding documents..."):
        n = pipeline.ingest(reset=True)
    st.sidebar.success(f"Indexed {n} chunks")

with st.sidebar:
    st.metric("Chunks in index", pipeline.store.count())

if "messages" not in st.session_state:
    st.session_state.messages = []

for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])

if question := st.chat_input("Ask something about your documents"):
    st.session_state.messages.append({"role": "user", "content": question})
    with st.chat_message("user"):
        st.markdown(question)

    with st.chat_message("assistant"):
        if pipeline.store.count() == 0:
            reply = "The index is empty. Add files to `data/docs/` and click **Re-index documents**."
            st.markdown(reply)
        else:
            hits = pipeline.retrieve(question, top_k)
            reply = st.write_stream(pipeline.stream(question, hits))
            with st.expander("Sources"):
                for i, hit in enumerate(hits, start=1):
                    st.markdown(f"**[{i}] {hit.source}, p. {hit.page}** · similarity {hit.score:.2f}")
                    st.caption(hit.text[:500] + ("…" if len(hit.text) > 500 else ""))
    st.session_state.messages.append({"role": "assistant", "content": reply})
